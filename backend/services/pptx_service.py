_DRAWERS = {
    "title":             _draw_title_slide,
    "content":           _draw_content_slide,
    "two-column":        _draw_two_column_slide,
    "chart-placeholder": _draw_chart_placeholder_slide,
    "image-text":        _draw_image_text_slide,
    "closing":           _draw_closing_slide,
}


def _draw_slide(slide, slide_data, palette: dict, font_name: str,
                logo_path: str | None) -> None:
    """Dispatch to the correct drawer based on slide layout type."""
    layout = slide_data.layout
    drawer = _DRAWERS.get(layout, _draw_content_slide)

    if layout in ("chart-placeholder", "image-text"):
        drawer(slide, slide_data.title, slide_data.talking_points,
               palette, font_name, logo_path, slide_data.placeholder_hint)
    else:
        drawer(slide, slide_data.title, slide_data.talking_points,
               palette, font_name, logo_path)


