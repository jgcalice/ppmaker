def _draw_header_bar(slide, title: str, palette: dict, font_name: str,
                     logo_path: str | None) -> None:
    """
    Shared header: dark-blue top bar, yellow accent line, title in bar,
    logo on the right edge of the bar.
    Used by: content, two-column, chart-placeholder, image-text.
    """
    BAR_H = 0.72       # top bar height in inches
    ACCENT_H = 0.055   # yellow line thickness

    # Dark-blue bar
    _add_rect(slide, 0, 0, 13.33, BAR_H, fill_hex=palette["secondary"])

    # Yellow accent line below bar
    _add_rect(slide, 0, BAR_H, 13.33, ACCENT_H, fill_hex=palette["accent"])

    # Title in bar
    _add_textbox(slide, 0.30, 0, 11.2, BAR_H,
                 text=title, font_name=font_name, font_size_pt=22,
                 bold=True, color_hex="#FFFFFF", align=PP_ALIGN.LEFT)

    # Logo
    _add_logo(slide, logo_path, left=12.15, top=0.22, width=0.94, height=0.28)


def _draw_title_slide(slide, title: str, talking_points: list[str],
                      palette: dict, font_name: str, logo_path: str | None) -> None:
    """
    Cover / title slide.
    Left ~42% = dark-navy panel. Right side = white with optional image area.
    """
    PANEL_W = 5.60

    # White full background
    _add_rect(slide, 0, 0, 13.33, 7.50, fill_hex=palette["background"])

    # Navy left panel
    _add_rect(slide, 0, 0, PANEL_W, 7.50, fill_hex=palette["secondary"])

    # Yellow accent stripe on top of panel
    _add_rect(slide, 0, 0, PANEL_W, 0.08, fill_hex=palette["accent"])

    # Yellow accent stripe at bottom of panel
    _add_rect(slide, 0, 7.42, PANEL_W, 0.08, fill_hex=palette["accent"])

    # Blue accent line on right side of panel (thin separator)
    _add_rect(slide, PANEL_W, 0, 0.04, 7.50, fill_hex=palette["primary"])

    # Title (main) in the panel - vertically centered
    subtitle = talking_points[0] if talking_points else ""
    _add_textbox(slide, 0.40, 1.80, PANEL_W - 0.60, 2.40,
                 text=title, font_name=font_name, font_size_pt=36,
                 bold=True, color_hex="#FFFFFF", align=PP_ALIGN.LEFT)

    # Subtitle / first talking point
    if subtitle:
        _add_textbox(slide, 0.40, 4.40, PANEL_W - 0.60, 1.20,
                     text=subtitle, font_name=font_name, font_size_pt=16,
                     bold=False, color_hex="#CCE0FF", align=PP_ALIGN.LEFT)

    # Additional talking points (if any) as small items below subtitle
    extras = talking_points[1:]
    if extras:
        _add_bullet_list(slide, 0.40, 5.80, PANEL_W - 0.60, 1.40,
                         extras, font_name=font_name, font_size_pt=11,
                         color_hex="#AACCEE", bullet=True)

    # Right side: decorative placeholder area
    _add_rect(slide, PANEL_W + 0.30, 0.50, 13.33 - PANEL_W - 0.60, 6.50,
              fill_hex=None, line_hex=palette["primary"], line_width_pt=0.5)
    _add_textbox(slide, PANEL_W + 0.30, 2.80, 13.33 - PANEL_W - 0.60, 1.00,
                 text="[ imagem / gráfico ]",
                 font_name=font_name, font_size_pt=11,
                 italic=True, color_hex=palette["primary"],
                 align=PP_ALIGN.CENTER)

    # Logo top-right
    _add_logo(slide, logo_path, left=12.15, top=0.22, width=0.94, height=0.28)


def _draw_content_slide(slide, title: str, talking_points: list[str],
                        palette: dict, font_name: str, logo_path: str | None) -> None:
    """Standard content slide: header bar + bulleted body."""
    _draw_header_bar(slide, title, palette, font_name, logo_path)

    # Body area
    body_top = 0.90
    _add_bullet_list(slide, 0.40, body_top, 12.53, 6.40,
                     talking_points, font_name=font_name, font_size_pt=16,
                     color_hex=palette["text"], bullet=True)


def _draw_two_column_slide(slide, title: str, talking_points: list[str],
                           palette: dict, font_name: str, logo_path: str | None) -> None:
    """Two-column layout: header bar, thin separator, points split left/right."""
    _draw_header_bar(slide, title, palette, font_name, logo_path)

    # Split talking points between two columns
    mid = max(1, len(talking_points) // 2)
    left_pts = talking_points[:mid]
    right_pts = talking_points[mid:]

    COL_TOP = 0.95
    COL_H = 6.30
    SEP_X = 6.82

    # Column header accent bars
    _add_rect(slide, 0.30, COL_TOP, 6.22, 0.06, fill_hex=palette["primary"])
    _add_rect(slide, SEP_X + 0.30, COL_TOP, 6.02, 0.06, fill_hex=palette["primary"])

    # Thin vertical separator
    _add_rect(slide, SEP_X, COL_TOP, 0.03, COL_H, fill_hex=palette["primary"])

    # Content
    _add_bullet_list(slide, 0.30, COL_TOP + 0.18, 6.22, COL_H - 0.18,
                     left_pts, font_name=font_name, font_size_pt=14,
                     color_hex=palette["text"], bullet=True)
    _add_bullet_list(slide, SEP_X + 0.30, COL_TOP + 0.18, 6.02, COL_H - 0.18,
                     right_pts, font_name=font_name, font_size_pt=14,
                     color_hex=palette["text"], bullet=True)


def _draw_chart_placeholder_slide(slide, title: str, talking_points: list[str],
                                   palette: dict, font_name: str,
                                   logo_path: str | None,
                                   placeholder_hint: str = "") -> None:
    """Chart-placeholder layout: header bar, talking points, large dashed area."""
    _draw_header_bar(slide, title, palette, font_name, logo_path)

    # Brief talking points at top (max 3, concise)
    short_pts = talking_points[:3]
    if short_pts:
        _add_bullet_list(slide, 0.40, 0.95, 12.53, 1.30,
                         short_pts, font_name=font_name, font_size_pt=13,
                         color_hex=palette["text"], bullet=True)

    # Large dashed placeholder
    hint = placeholder_hint or "[ Inserir gráfico / tabela ]"
    _add_dashed_placeholder(slide, 0.60, 2.50, 12.13, 4.50,
                            hint=hint, color_hex=palette["primary"],
                            font_name=font_name)


def _draw_image_text_slide(slide, title: str, talking_points: list[str],
                           palette: dict, font_name: str, logo_path: str | None,
                           placeholder_hint: str = "") -> None:
    """Image-left, text-right layout."""
    _draw_header_bar(slide, title, palette, font_name, logo_path)

    IMG_W = 6.20
    TXT_X = IMG_W + 0.50
    CONTENT_TOP = 0.90

    # Left image placeholder
    _add_rect(slide, 0.30, CONTENT_TOP, IMG_W, 6.35,
              fill_hex="#EEF3FB",
              line_hex=palette["primary"], line_width_pt=0.8)
    hint = placeholder_hint or "[ Inserir imagem ]"
    _add_textbox(slide, 0.30, CONTENT_TOP + 2.80, IMG_W, 0.80,
                 text=hint, font_name=font_name, font_size_pt=12,
                 italic=True, color_hex=palette["primary"], align=PP_ALIGN.CENTER)

    # Right text content
    _add_bullet_list(slide, TXT_X, CONTENT_TOP + 0.30, 13.33 - TXT_X - 0.30, 5.80,
                     talking_points, font_name=font_name, font_size_pt=14,
                     color_hex=palette["text"], bullet=True)


def _draw_closing_slide(slide, title: str, talking_points: list[str],
                        palette: dict, font_name: str, logo_path: str | None) -> None:
    """Closing / thank-you slide: full dark-blue background, white centered title."""
    # Dark-blue full background
    _add_rect(slide, 0, 0, 13.33, 7.50, fill_hex=palette["secondary"])

    # Yellow accent bars top and bottom
    _add_rect(slide, 0, 0, 13.33, 0.12, fill_hex=palette["accent"])
    _add_rect(slide, 0, 7.38, 13.33, 0.12, fill_hex=palette["accent"])

    # Blue side accents
    _add_rect(slide, 0, 0, 0.08, 7.50, fill_hex=palette["primary"])
    _add_rect(slide, 13.25, 0, 0.08, 7.50, fill_hex=palette["primary"])

    # Large centered title
    _add_textbox(slide, 1.0, 1.80, 11.33, 2.50,
                 text=title, font_name=font_name, font_size_pt=52,
                 bold=True, color_hex="#FFFFFF", align=PP_ALIGN.CENTER)

    # Subtitle / talking points below
    if talking_points:
        _add_textbox(slide, 1.0, 4.50, 11.33, 1.80,
                     text="  •  ".join(talking_points),
                     font_name=font_name, font_size_pt=14,
                     color_hex="#CCE0FF", align=PP_ALIGN.CENTER)

    # Logo top-right
    _add_logo(slide, logo_path, left=12.15, top=0.22, width=0.94, height=0.28)


