def _find_stencil_file(template_path: str) -> str | None:
    """
    Look for any .pptx file in ../../template_padrao/local/example/ relative
    to template_path.  Returns the first match, or None.
    """
    template_dir = os.path.dirname(os.path.abspath(template_path))
    example_dir  = os.path.normpath(
        os.path.join(template_dir, "..", "..", "template_padrao", "local", "example")
    )

    if not os.path.isdir(example_dir):
        # Try one level up (template_path may already be inside backend/)
        example_dir = os.path.normpath(
            os.path.join(template_dir, "..", "..", "..", "template_padrao", "local", "example")
        )

    if not os.path.isdir(example_dir):
        logger.debug("Stencil example dir not found: %s", example_dir)
        return None

    import glob as _glob
    pptx_files = sorted(_glob.glob(os.path.join(example_dir, "*.pptx")))
    if pptx_files:
        logger.debug("Found stencil: %s", pptx_files[0])
        return pptx_files[0]

    return None


def _generate_pptx_stencil(
    outline: StorytellingOutline,
    stencil_path: str,
    catalog_path: str,
    template_meta: TemplateInfo,
) -> io.BytesIO:
    """
    Render the deck using the stencil + catalog approach.

    Imports StencilRenderer and VisualDirector lazily to avoid circular
    imports and to keep the fallback path self-contained.
    """
    import json as _json

    from services.render_from_template import StencilRenderer
    from services.visual_director import VisualDirector

    # Load catalog
    with open(catalog_path, "r", encoding="utf-8") as fh:
        catalog = _json.load(fh)

    # Locate brand_tokens.json next to layout_catalog.json
    tokens_path = os.path.join(os.path.dirname(catalog_path), "brand_tokens.json")
    if os.path.isfile(tokens_path):
        with open(tokens_path, "r", encoding="utf-8") as fh:
            brand_tokens = _json.load(fh)
    else:
        # Build a minimal brand_tokens from template_meta
        palette = template_meta.palette.model_dump()
        brand_tokens = {
            "palette":       palette,
            "typography": {
                "title":    {"font": template_meta.font_title or "Avantt", "size_pt": 28, "bold": True,  "color": palette.get("secondary", "#00328D")},
                "subtitle": {"font": template_meta.font_title or "Avantt", "size_pt": 20, "bold": True,  "color": palette.get("secondary", "#00328D")},
                "body":     {"font": template_meta.font_body  or "Avantt", "size_pt": 9,  "bold": False, "color": palette.get("text", "#00328D")},
                "kpi":      {"font": template_meta.font_title or "Avantt", "size_pt": 28, "bold": True,  "color": palette.get("accent", "#FFA41B")},
                "label":    {"font": template_meta.font_body  or "Avantt", "size_pt": 8,  "bold": False, "color": palette.get("primary", "#0766FF")},
            },
            "slide_width_in":  13.33,
            "slide_height_in": 7.5,
        }

    renderer = StencilRenderer(stencil_path, catalog, brand_tokens)

    # VisualDirector without an API key (deterministic only)
    vd = VisualDirector(catalog_path, tokens_path if os.path.isfile(tokens_path) else catalog_path)

    return renderer.render(outline, visual_director=vd)


def _generate_pptx_programmatic(
    outline: StorytellingOutline,
    template_path: str,
    template_meta: TemplateInfo,
) -> io.BytesIO:
    """
    Original programmatic renderer.

    Draws all slides from scratch using python-pptx shape primitives.
    The template file only provides the base theme/fonts.
    """
    # Open with bytes to handle paths with spaces
    try:
        with open(template_path, "rb") as fh:
            prs = Presentation(io.BytesIO(fh.read()))
    except Exception:
        prs = Presentation(template_path)

    # Ensure slide size is widescreen 16:9
    prs.slide_width  = Inches(13.33)
    prs.slide_height = Inches(7.50)

    palette   = template_meta.palette.model_dump()
    font_name = template_meta.font_title or "Avantt"

    # Logo path: sits next to the template JSON / PPTX
    template_dir = os.path.dirname(template_path)
    logo_path    = os.path.join(template_dir, "logo.png")

    _remove_existing_slides(prs)

    # Use the first available blank layout
    blank_layout = prs.slide_layouts[0]
    for layout in prs.slide_layouts:
        if "blank" in layout.name.lower() or "em branco" in layout.name.lower():
            blank_layout = layout
            break

    for slide_data in outline.slides:
        slide = prs.slides.add_slide(blank_layout)
        _draw_slide(slide, slide_data, palette, font_name, logo_path)

    buffer = io.BytesIO()
    prs.save(buffer)
    buffer.seek(0)

    if buffer.getbuffer().nbytes > 50 * 1024 * 1024:
        raise ValueError("Generated PPTX exceeds 50MB size limit")

    return buffer


