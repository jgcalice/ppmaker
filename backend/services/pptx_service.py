"""
PPTX generation service.

Three rendering paths are supported, tried in order of preference:

  1. XML-based (preferred)
     Unpacks the template PPTX, edits each slide's XML directly, then repacks.
     Preserves 100% of template formatting (fonts, animations, SmartArt).
     Requires: scripts/office/unpack.py, scripts/add_slide.py, scripts/clean.py,
               scripts/office/pack.py  (all in PROJECT_ROOT/scripts/).
     Controlled via: PPTX_RENDERER=auto|xml

  2. Stencil-based
     Clones slides from the brand stencil template, replaces text/images while
     preserving all original formatting.  Requires:
       - A .pptx stencil file in template_padrao/local/example/
       - tools/layout_catalog.json  (generated by tools/inspect_template.py)
     Controlled via: PPTX_RENDERER=auto|stencil

  3. Programmatic (fallback)
     Draws slides from scratch using python-pptx shapes.  Always works, but
     produces a plain visual style that does not match the brand stencil.
     Controlled via: PPTX_RENDERER=auto|programmatic

Environment variable:
    PPTX_RENDERER=auto           (default) — try xml → stencil → programmatic
    PPTX_RENDERER=xml            — force XML path only (raises on failure)
    PPTX_RENDERER=stencil        — force stencil path only
    PPTX_RENDERER=programmatic   — force programmatic path only

The public entry-point is generate_pptx().
"""

