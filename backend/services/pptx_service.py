def _rgb(hex_color: str) -> RGBColor:
    h = hex_color.lstrip("#")
    return RGBColor(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def _in(inches: float) -> Emu:
    return Inches(inches)


def _add_rect(slide, left, top, width, height, fill_hex: str | None = None,
              line_hex: str | None = None, line_width_pt: float = 0):
    """Add a filled/outlined rectangle shape."""
    shape = slide.shapes.add_shape(
        1,  # MSO_SHAPE.RECTANGLE
        _in(left), _in(top), _in(width), _in(height)
    )
    if fill_hex:
        shape.fill.solid()
        shape.fill.fore_color.rgb = _rgb(fill_hex)
    else:
        shape.fill.background()

    if line_hex:
        shape.line.color.rgb = _rgb(line_hex)
        shape.line.width = Pt(line_width_pt)
    else:
        shape.line.fill.background()
    return shape


def _add_textbox(slide, left, top, width, height,
                 text: str, font_name: str, font_size_pt: float,
                 bold: bool = False, color_hex: str = "#1A1A1A",
                 align: PP_ALIGN = PP_ALIGN.LEFT,
                 wrap: bool = True, italic: bool = False) -> None:
    """Add a text box with a single paragraph/run of text."""
    txBox = slide.shapes.add_textbox(_in(left), _in(top), _in(width), _in(height))
    tf = txBox.text_frame
    tf.word_wrap = wrap
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.name = font_name
    run.font.size = Pt(font_size_pt)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = _rgb(color_hex)


def _add_bullet_list(slide, left, top, width, height,
                     points: list[str], font_name: str,
                     font_size_pt: float = 14, color_hex: str = "#1A1A1A",
                     bullet: bool = True) -> None:
    """Add a text box with multiple bullet point paragraphs."""
    txBox = slide.shapes.add_textbox(_in(left), _in(top), _in(width), _in(height))
    tf = txBox.text_frame
    tf.word_wrap = True
    for i, point in enumerate(points):
        if i == 0:
            p = tf.paragraphs[0]
        else:
            p = tf.add_paragraph()
        p.space_after = Pt(6)
        run = p.add_run()
        run.text = ("• " if bullet else "") + point
        run.font.name = font_name
        run.font.size = Pt(font_size_pt)
        run.font.color.rgb = _rgb(color_hex)


def _add_logo(slide, logo_path: str | None,
              left: float, top: float, width: float, height: float) -> None:
    """Add logo image if the file exists."""
    if logo_path and os.path.isfile(logo_path):
        slide.shapes.add_picture(logo_path, _in(left), _in(top),
                                 _in(width), _in(height))


def _add_dashed_placeholder(slide, left, top, width, height,
                             hint: str, color_hex: str, font_name: str) -> None:
    """Dashed rectangle with hint text for chart/image placeholders."""
    shape = _add_rect(slide, left, top, width, height,
                      fill_hex=None, line_hex=color_hex, line_width_pt=1.5)
    # dash style: 4 = dash
    shape.line.dash_style = 4

    tf = shape.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.CENTER
    run = p.add_run()
    run.text = hint
    run.font.name = font_name
    run.font.size = Pt(12)
    run.font.italic = True
    run.font.color.rgb = _rgb(color_hex)


