"""Tests for pptx_service — PPTX generation, slide count, titles, placeholders."""

import io
from pathlib import Path
from unittest.mock import patch

import pytest
from pptx import Presentation as PptxPresentation


def _make_blank_pptx(path: Path):
    """Create a minimal blank .pptx template file for testing."""
    prs = PptxPresentation()
    prs.save(str(path))
    return path


@pytest.fixture
def pptx_template(tmp_path):
    """Create a minimal PPTX template file."""
    pptx_path = tmp_path / "test-template.pptx"
    _make_blank_pptx(pptx_path)
    return pptx_path


def test_generated_pptx_is_valid_file(sample_outline_model, sample_template_meta, pptx_template):
    """Generated bytes must be openable as a valid PPTX."""
    from services.pptx_service import generate_pptx

    buffer = generate_pptx(sample_outline_model, str(pptx_template), sample_template_meta)
    assert isinstance(buffer, io.BytesIO)

    # Must be openable as a valid PPTX
    prs = PptxPresentation(buffer)
    assert prs is not None


