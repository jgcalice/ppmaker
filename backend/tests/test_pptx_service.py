def test_generate_pptx_renderer_env_programmatic(
    sample_outline_model, sample_template_meta, pptx_template, monkeypatch
):
    """PPTX_RENDERER=programmatic must use the programmatic path exclusively.

    We verify this by patching the XML and stencil helpers and confirming they
    are never called when the env var forces 'programmatic'.
    """
    # Arrange
    monkeypatch.setenv("PPTX_RENDERER", "programmatic")

    from services.pptx_service import generate_pptx

    xml_called = []
    stencil_called = []

    with patch(
        "services.pptx_service._generate_pptx_xml_path",
        side_effect=lambda *a, **kw: xml_called.append(True),
    ), patch(
        "services.pptx_service._generate_pptx_stencil",
        side_effect=lambda *a, **kw: stencil_called.append(True),
    ):
        # Act
        buffer = generate_pptx(sample_outline_model, str(pptx_template), sample_template_meta)

    # Assert
    assert isinstance(buffer, io.BytesIO), "Result must be io.BytesIO"
    assert not xml_called, "XML renderer must NOT be called when PPTX_RENDERER=programmatic"
    assert not stencil_called, "Stencil renderer must NOT be called when PPTX_RENDERER=programmatic"


def test_generate_pptx_renderer_env_auto_fallback(
    sample_outline_model, sample_template_meta, pptx_template, monkeypatch
):
    """PPTX_RENDERER=auto must fall back to programmatic when XML renderer fails.

    We simulate a broken XML renderer and verify the service still returns a
    valid PPTX using the programmatic fallback path.
    """
    # Arrange
    monkeypatch.setenv("PPTX_RENDERER", "auto")

    from services.pptx_service import generate_pptx

    def _raise_xml(*args, **kwargs):
        raise RuntimeError("Simulated XML renderer failure")

    with patch("services.pptx_service._generate_pptx_xml_path", side_effect=_raise_xml):
        # Act — should NOT raise; programmatic path must take over
        buffer = generate_pptx(sample_outline_model, str(pptx_template), sample_template_meta)

    # Assert
    assert isinstance(buffer, io.BytesIO), "Fallback must return io.BytesIO"
    prs = PptxPresentation(buffer)
    assert len(prs.slides) == sample_outline_model.total_slides, (
        "Programmatic fallback must produce correct slide count"
    )


def test_generate_pptx_renderer_auto_succeeds(
    sample_outline_model, sample_template_meta, pptx_template, monkeypatch
):
    """PPTX_RENDERER=auto with a functioning XML renderer must return a valid BytesIO.

    We mock the XML renderer to return a programmatically generated PPTX so the
    test is self-contained and does not require real scripts on PATH.
    """
    # Arrange
    monkeypatch.setenv("PPTX_RENDERER", "auto")

    from services.pptx_service import generate_pptx, _generate_pptx_programmatic

    def _fake_xml(outline, template_path, template_meta):
        # Return a valid programmatic PPTX to simulate XML renderer success
        return _generate_pptx_programmatic(outline, template_path, template_meta)

    with patch("services.pptx_service._generate_pptx_xml_path", side_effect=_fake_xml):
        # Act
        buffer = generate_pptx(sample_outline_model, str(pptx_template), sample_template_meta)

    # Assert
    assert isinstance(buffer, io.BytesIO), "Auto mode must return io.BytesIO"
    assert buffer.getbuffer().nbytes > 0, "Buffer must not be empty"
    prs = PptxPresentation(buffer)
    assert len(prs.slides) == sample_outline_model.total_slides



def test_replace_slide_content_keeps_label_unchanged_by_default(monkeypatch):
    """Stencil flow must preserve decorative LABEL zones unless explicitly writable."""
    from services.render_from_template import StencilRenderer
    from models.schemas import SlideOutline

    class _TF:
        def __init__(self, text):
            self.text = text

    class _Shape:
        def __init__(self, text):
            self.text_frame = _TF(text)

    label_shape = _Shape("01")
    title_shape = _Shape("Template title")

    zones = [
        {"shape": label_shape, "role": "LABEL"},
        {"shape": title_shape, "role": "TITLE"},
    ]

    monkeypatch.setattr("services.render_from_template.classify_text_zones", lambda slide: zones)

    writes = []

    def _fake_replace_text(tf, new_text, max_chars=500):
        writes.append(new_text)
        tf.text = new_text

    monkeypatch.setattr("services.render_from_template.replace_text_preserving_format", _fake_replace_text)

    renderer = StencilRenderer("dummy.pptx", {"catalog": []}, {})
    slide_data = SlideOutline(
        index=0,
        layout="content",
        title="Updated title",
        talking_points=["First point", "Second point"],
        has_placeholder=False,
        placeholder_hint="",
    )

    renderer._replace_slide_content(slide=object(), slide_data=slide_data, layout_entry=None)

    assert label_shape.text_frame.text == "01"
    assert title_shape.text_frame.text == "Updated title"
    assert "First point" not in writes


